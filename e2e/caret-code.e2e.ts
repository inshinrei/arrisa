test("shift-enter lines in a code block: up and down keep CodeBlock", async ({page}) => {
    await openCompose(page)
    await composeBox(page).click()
    await typeFence(page, "py")
    await page.keyboard.type("ab")
    await page.keyboard.press("Shift+Enter")
    await page.keyboard.type("cd")
    let lower = await caretSnap(page)
    expect(lower.block).toBe("CodeBlock")
    expect(lower.blockText).toMatch(/ab/)
    expect(lower.blockText).toMatch(/cd/)
    expect(lower.names).toEqual(["CodeBlock"])
    let cd = await findText(page, "cd")
    let ab = await findText(page, "ab")
    await page.keyboard.press("ArrowUp")
    let upper = await caretSnap(page)
    expect(upper.block).toBe("CodeBlock")
    expect(upper.head).toBeGreaterThanOrEqual(ab.from)
    expect(upper.head).toBeLessThanOrEqual(ab.to)
    await page.keyboard.press("ArrowDown")
    let back = await caretSnap(page)
    expect(back.block).toBe("CodeBlock")
    expect(back.head).toBeGreaterThanOrEqual(cd.from)
    expect(back.head).toBeLessThanOrEqual(cd.to)
    await page.keyboard.press("Home")
    let lineStart = await caretSnap(page)
    expect(lineStart.head).toBe(cd.from)
    await page.keyboard.press("End")
    let lineEnd = await caretSnap(page)
    expect(lineEnd.head).toBe(cd.to)
})

