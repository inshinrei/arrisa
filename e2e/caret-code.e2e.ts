test("word motion inside code skips identifiers", async ({page}) => {
    await openCompose(page)
    await composeBox(page).click()
    await typeFence(page, "py")
    await page.keyboard.type("print value")
    let value = await findText(page, "value")
    await page.keyboard.press(wordKey("left"))
    let atValue = await caretSnap(page)
    expect(atValue.block).toBe("CodeBlock")
    expect(atValue.head).toBe(value.from)
    await page.keyboard.press(wordKey("right"))
    let after = await caretSnap(page)
    expect(after.head).toBe(value.to)
    expect(after.block).toBe("CodeBlock")
})

test("caret in an empty code block is vertical and typing stays inside", async ({page}) => {
    await openCompose(page)
    await composeBox(page).click()
    await typeFence(page, "py")
    await waitFrames(page)
    let empty = await caretSnap(page)
    expect(empty.block).toBe("CodeBlock")
    expect(empty.blockText).toBe("")
    expect(empty.cursorClass).toMatch(/arrisa-cursor-v/)
    expect(empty.cursorClass).not.toMatch(/arrisa-cursor-h/)
    await page.keyboard.type("x")
    let typed = await caretSnap(page)
    expect(typed.block).toBe("CodeBlock")
    expect(typed.blockText).toBe("x")
})
