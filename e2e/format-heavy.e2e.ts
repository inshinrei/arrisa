import {expect, test} from "@playwright/test"
import {composeBox, e2e, openCompose} from "./helpers"
import {clickDocPos, findText, selectAllKey, waitFrames} from "./caret"
import {dump, hasFlag, MARK_KEYS, selectNeedle} from "./format"

test("overlapping bold then italic on a later slice dumps both runs", async ({page}) => {
    await openCompose(page)
    await composeBox(page).click()
    await page.keyboard.type("abcd")
    await selectNeedle(page, "abc")
    await page.keyboard.press(MARK_KEYS.bold)
    // "cd" spans the bold split; findText is per text node.
    let c = await findText(page, "c")
    let d = await findText(page, "d")
    await clickDocPos(page, c.from, 1)
    await clickDocPos(page, d.to, -1, {shift: true})
    await page.keyboard.press(MARK_KEYS.italic)
    let ft = await dump(page)
    expect(ft.text).toBe("abcd")
    expect(hasFlag(ft, "bold", 0, 3)).toBe(true)
    expect(hasFlag(ft, "italic", 2, 2)).toBe(true)
})

test("bold around emoji uses UTF-16 entity length", async ({page}) => {
    await openCompose(page)
    await composeBox(page).click()
    await page.keyboard.type("a😀b")
    await page.keyboard.press(selectAllKey())
    await page.keyboard.press(MARK_KEYS.bold)
    let ft = await dump(page)
    expect(ft.text).toBe("a😀b")
    expect(ft.text.length).toBe(4)
    expect(hasFlag(ft, "bold", 0, 4)).toBe(true)
})

test("select-all bold covers two paragraphs", async ({page}) => {
    await openCompose(page)
    await composeBox(page).click()
    await page.keyboard.type("one")
    await page.keyboard.press("Enter")
    await page.keyboard.type("two")
    await page.keyboard.press(selectAllKey())
    await page.keyboard.press(MARK_KEYS.bold)
    let ft = await dump(page)
    expect(ft.text).toMatch(/one/)
    expect(ft.text).toMatch(/two/)
    expect(ft.entities?.some((e) => e.type == "bold" && e.length >= 3)).toBe(true)
})

test("heavy announcement dumps list, quote, code, marks, mention, and auto url", async ({page}) => {
    await openCompose(page)
    await composeBox(page).click()
    await page.keyboard.type("Ship notes")
    await page.keyboard.press("Enter")
    await page.keyboard.type("Deadline Friday")
    await selectNeedle(page, "Deadline")
    await page.keyboard.press(MARK_KEYS.bold)
    let friday = await findText(page, "Friday")
    await clickDocPos(page, friday.to, -1)
    // Click/Enter update logical selection immediately; DOM range syncs on rAF.
    await waitFrames(page)
    await page.keyboard.press("Enter")
    await waitFrames(page)
    await page.keyboard.type("- API review")
    await page.keyboard.press("Enter")
    await page.keyboard.type("docs pass")
    await page.keyboard.press("Enter")
    await page.keyboard.press("Enter")
    await waitFrames(page)
    await page.keyboard.type("> keep offsets")
    await page.keyboard.press("Enter")
    await page.keyboard.press("Enter")
    await page.keyboard.type("`api.dump`")
    await page.keyboard.press("Enter")
    await page.keyboard.type("See https://example.com/ship")
    await page.keyboard.press("Enter")
    await e2e(page, (api) => {
        api.insertText("@al")
        let text = api.dump().text
        api.insertMention({userId: "user-alice", label: "Alice", from: text.length - 3, to: text.length})
    })
    let ft = await dump(page, {autoDetect: true})
    expect(ft.text).toContain("Ship notes")
    expect(ft.text).toContain("Deadline")
    expect(ft.text).toContain("API review")
    expect(ft.text).toContain("keep offsets")
    expect(ft.text).toContain("api.dump")
    expect(ft.text).toContain("https://example.com/ship")
    expect(ft.entities?.some((e) => e.type == "bold")).toBe(true)
    expect(ft.entities?.some((e) => e.type == "unordered_list")).toBe(true)
    expect(ft.entities?.some((e) => e.type == "blockquote")).toBe(true)
    expect(ft.entities?.some((e) => e.type == "code")).toBe(true)
    expect(ft.entities?.some((e) => e.type == "url")).toBe(true)
    expect(ft.entities?.some((e) => e.type == "mention_name" && e.userId == "user-alice")).toBe(true)
})

test("send button writes FormattedText with autoDetect and leaves the draft", async ({page}) => {
    await openCompose(page)
    await composeBox(page).click()
    await page.keyboard.type("**go** https://example.com")
    await page.locator("#btn-send").click()
    let out = await page.locator("#chat-out").textContent()
    expect(out).toContain("FormattedText")
    expect(out).toContain("bold")
    let ft = await dump(page)
    expect(ft.text).toContain("go")
    expect(hasFlag(ft, "bold", 0, 2)).toBe(true)
})
